using System.Buffers.Binary;
using System.Text;
using System.Text.Json.Nodes;

namespace Mosaic.Core.Downloads;

/// <summary>How downloads are shared with Free Download Manager. Raw values match macOS.</summary>
public enum FdmMode
{
    /// <summary>Mosaic downloads everything itself.</summary>
    Off,
    /// <summary>Mosaic asks, for each download, whether FDM should take it.</summary>
    Ask,
    /// <summary>Downloads go to FDM (subject to the size threshold).</summary>
    Always,
}

public static class FdmModes
{
    public static string Id(this FdmMode mode) => mode.ToString().ToLowerInvariant();

    public static FdmMode? FromId(string? id) => id switch
    {
        "off" => FdmMode.Off,
        "ask" => FdmMode.Ask,
        "always" => FdmMode.Always,
        _ => null,
    };

    public static string Title(this FdmMode mode) => mode switch
    {
        FdmMode.Off => "Off",
        FdmMode.Ask => "Ask for each download",
        _ => "Always use Free Download Manager",
    };
}

/// <summary>What <see cref="FdmPolicy.Decide"/> concluded.</summary>
public enum FdmDecision { UseEngine, AskUser, SendToFdm }

/// <summary>Decides whether a download goes to Free Download Manager.</summary>
/// <param name="Mode">Off, ask or always.</param>
/// <param name="MinimumBytes">Downloads known to be smaller than this stay in Mosaic; 0 sends every size.</param>
public sealed record FdmPolicy(FdmMode Mode = FdmMode.Off, long MinimumBytes = 0)
{
    /// <summary>
    /// Schemes FDM can fetch by itself. Anything else (blob:, data:, file:, pages generated by the
    /// browser) exists only inside the engine and must stay there.
    /// </summary>
    public static readonly IReadOnlySet<string> SupportedSchemes = new HashSet<string> { "http", "https", "ftp" };

    public static bool Supports(string url) =>
        Uri.TryCreate(url, UriKind.Absolute, out var uri) && SupportedSchemes.Contains(uri.Scheme.ToLowerInvariant());

    /// <summary>
    /// <paramref name="totalBytes"/> is null (or negative) when the server did not give a size; such
    /// downloads are treated as large enough.
    /// </summary>
    public FdmDecision Decide(string url, long? totalBytes, bool fdmInstalled)
    {
        if (!fdmInstalled || Mode == FdmMode.Off || !Supports(url)) return FdmDecision.UseEngine;
        if (MinimumBytes > 0 && totalBytes is { } size && size >= 0 && size < MinimumBytes) return FdmDecision.UseEngine;
        return Mode == FdmMode.Ask ? FdmDecision.AskUser : FdmDecision.SendToFdm;
    }
}

/// <summary>One download as Free Download Manager's browser integration describes it.</summary>
/// <param name="Url">The file's address (after redirects).</param>
/// <param name="OriginalUrl">The address first requested, if different.</param>
/// <param name="Referrer">The page the download started from.</param>
/// <param name="UserAgent">The engine's User-Agent.</param>
/// <param name="Cookies">"name=value; name2=value2", only when the user allowed passing cookies.</param>
public sealed record FdmDownloadRequest(
    string Url, string? OriginalUrl = null, string? Referrer = null, string? UserAgent = null, string? Cookies = null);

/// <summary>How FDM answered a <c>create_downloads</c> message.</summary>
public abstract record FdmOutcome
{
    private FdmOutcome() { }

    public sealed record Accepted : FdmOutcome;
    public sealed record CancelledByUser : FdmOutcome;
    public sealed record Failed(string Message) : FdmOutcome;
}

/// <summary>
/// The messages FDM's browser-integration helper (<c>wenativehost</c>, a WebExtension native
/// messaging host) understands. It reads and writes messages framed the native-messaging way:
/// a 32-bit length in native (little-endian) byte order, then that many bytes of UTF-8 JSON.
/// </summary>
/// <remarks>
/// Port of <c>FDMNativeMessage</c> (FreeDownloadManagerProtocol.swift), learned from FDM's own
/// browser extension, which talks to the same helper: a <c>handshake</c> first, then
/// <c>create_downloads</c>. FDM answers <c>create_downloads</c> once the user has confirmed or
/// cancelled its "New download" dialog (<c>result</c> "0" = cancelled), or at once with
/// <c>error</c> set when it cannot fetch the URL.
/// </remarks>
public static class FdmNativeMessage
{
    /// <summary>Largest message accepted from the helper (native messaging caps host replies at 1 MB).</summary>
    public const int MaxMessageLength = 1024 * 1024;

    public static byte[] Frame(JsonObject message)
    {
        var json = Encoding.UTF8.GetBytes(message.ToJsonString());
        var data = new byte[4 + json.Length];
        BinaryPrimitives.WriteUInt32LittleEndian(data, (uint)json.Length);
        json.CopyTo(data, 4);
        return data;
    }

    /// <summary>Removes and returns every complete message at the start of <paramref name="buffer"/>.</summary>
    public static List<JsonObject> TakeMessages(List<byte> buffer)
    {
        var messages = new List<JsonObject>();
        while (buffer.Count >= 4)
        {
            var length = (int)BinaryPrimitives.ReadUInt32LittleEndian([buffer[0], buffer[1], buffer[2], buffer[3]]);
            if (length < 0 || length > MaxMessageLength)
            {
                // Not a native-messaging stream; nothing after this can be trusted.
                buffer.Clear();
                break;
            }
            if (buffer.Count < 4 + length) break;
            var body = buffer.GetRange(4, length).ToArray();
            buffer.RemoveRange(0, 4 + length);
            try
            {
                if (JsonNode.Parse(body) is JsonObject message) messages.Add(message);
            }
            catch (System.Text.Json.JsonException)
            {
            }
        }
        return messages;
    }

    public static JsonObject Handshake(string id) => new()
    {
        ["id"] = id,
        ["type"] = "handshake",
        ["handshake"] = new JsonObject { ["api_version"] = "2", ["browser"] = "Mosaic" },
    };

    public static JsonObject CreateDownloads(string id, IEnumerable<FdmDownloadRequest> requests)
    {
        var downloads = new JsonArray();
        foreach (var request in requests)
        {
            var entry = new JsonObject
            {
                ["url"] = request.Url,
                ["originalUrl"] = request.OriginalUrl ?? request.Url,
                ["httpReferer"] = request.Referrer ?? "",
                ["documentUrl"] = request.Referrer ?? "",
                ["httpPostData"] = "",
            };
            if (!string.IsNullOrEmpty(request.UserAgent)) entry["userAgent"] = request.UserAgent;
            if (!string.IsNullOrEmpty(request.Cookies)) entry["httpCookies"] = request.Cookies;
            downloads.Add(entry);
        }
        return new JsonObject
        {
            ["id"] = id,
            ["type"] = "create_downloads",
            ["create_downloads"] = new JsonObject
            {
                ["catchedDownloads"] = "1",
                ["waitResponse"] = "1",
                ["downloads"] = downloads,
            },
        };
    }

    public static FdmOutcome Outcome(JsonObject response)
    {
        if (Text(response["error"]) is { Length: > 0 } error) return new FdmOutcome.Failed(error);
        if (Text(response["result"]) == "0") return new FdmOutcome.CancelledByUser();
        return new FdmOutcome.Accepted();
    }

    /// <summary>The helper asking something of the browser (rather than answering): has <c>isResponse: false</c>.</summary>
    public static bool IsRequest(JsonObject message) =>
        message["isResponse"] is JsonValue value && value.TryGetValue(out bool isResponse) && !isResponse;

    /// <summary>The reply that declines a request from the helper (cookie queries and the like).</summary>
    public static JsonObject Decline(JsonObject request) => new()
    {
        ["id"] = request["id"]?.DeepClone(),
        ["type"] = request["type"]?.DeepClone() ?? "",
        ["error"] = "not_implemented",
        ["isResponse"] = true,
    };

    internal static string? Text(JsonNode? node) => node switch
    {
        JsonValue value when value.TryGetValue(out string? text) => text,
        JsonValue value when value.TryGetValue(out long number) => number.ToString(System.Globalization.CultureInfo.InvariantCulture),
        _ => null,
    };
}
